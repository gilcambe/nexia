'use strict';
// Rodapé antigo ("Pedido pelo Cortex no celular por ...") nunca aparece para o dono.
const RODAPE = /\n*_(Pedido )?[Pp]elo Cortex no celular por [^\n]*_\s*$/;
const limpar = (t) => String(t || '').trim().replace(RODAPE, '').trim();
// Cortex no celular: um pedido com a conversa inteira (comentários) e os PRs que o Cortex abriu para ele.
const { resumo, nomes, frase, REPO } = require('./pedidos-gh');

function criarDetalhe(gh) {
  const busca = (q, extra = '') => gh('/search/issues?per_page=30' + extra + '&q=' + encodeURIComponent(q));
  async function prsDe(i) {
    const termo = frase(i.body);
    if (!termo) return [];
    const r = await busca('repo:' + REPO + ' is:pr in:body "' + termo + '"', '&sort=created&order=desc');
    return Promise.all((r.items || []).slice(0, 5).map(async (x) => {
      const pr = await gh('/repos/' + REPO + '/pulls/' + x.number);
      let ci = null;
      if (pr.state === 'open') {
        const runs = (await gh('/repos/' + REPO + '/commits/' + pr.head.sha + '/check-runs?per_page=50').catch(() => ({}))).check_runs || [];
        ci = runs.some((c) => c.status !== 'completed') ? 'rodando'
          : runs.some((c) => ['failure', 'timed_out', 'cancelled'].includes(c.conclusion)) ? 'vermelho' : runs.length ? 'verde' : 'sem-teste';
      }
      return {
        numero: pr.number, titulo: String(pr.title || '').slice(0, 120), link: pr.html_url, ramo: pr.head.ref,
        estado: pr.merged_at ? 'juntado' : pr.state === 'open' ? (pr.draft ? 'rascunho' : 'aberto') : 'fechado',
        ci, automerge: nomes(pr).includes('automerge'), quando: pr.updated_at,
      };
    }));
  }

  async function detalhe(n) {
    const i = await gh('/repos/' + REPO + '/issues/' + Number(n));
    if (i.pull_request) throw new Error('Isso é um PR, não um pedido.');
    const [coms, prs] = await Promise.all([
      gh('/repos/' + REPO + '/issues/' + i.number + '/comments?per_page=100'),
      prsDe(i).catch(() => []),
    ]);
    const conversa = [{ quem: (i.user || {}).login || '?', quando: i.created_at, texto: limpar(i.body) }]
      .concat(coms.map((c) => ({ quem: (c.user || {}).login || '?', quando: c.created_at, texto: String(c.body || '').replace(/\n---\n_Generated by[^\n]*_\s*$/, '').trim().replace(RODAPE, '').trim() })));
    return { ...resumo(i), rotulos: nomes(i), conversa, prs };
  }

  return detalhe;
}

module.exports = { criarDetalhe };
