'use strict';
// Rodapé antigo ("Pedido pelo Cortex no celular por ...") nunca aparece para o dono.
const RODAPE = /\n*_(Pedido )?[Pp]elo Cortex no celular por [^\n]*_\s*$/;
const limpar = (t) => String(t || '').trim().replace(RODAPE, '').trim();
// Cortex no celular: um pedido com a conversa inteira (comentários) e os PRs que o Cortex abriu para ele.
const { resumo, nomes, frase, REPO } = require('./pedidos-gh');

function criarDetalhe(gh) {
  const busca = (q, extra = '') => gh('/search/issues?per_page=30' + extra + '&q=' + encodeURIComponent(q));
  async function prsDe(i) {
    const termo = frase(i.body);
    if (!termo) return [];
    const r = await busca('repo:' + REPO + ' is:pr in:body "' + termo + '"', '&sort=created&order=desc');
    return Promise.all((r.items || []).slice(0, 5).map(async (x) => {
      const pr = await gh('/repos/' + REPO + '/pulls/' + x.number);
      let ci = null;
      if (pr.state === 'open') {
        const runs = (await gh('/repos/' + REPO + '/commits/' + pr.head.sha + '/check-runs?per_page=50').catch(() => ({}))).check_runs || [];
        ci = runs.some((c) => c.status !== 'completed') ? 'rodando'
          : runs.some((c) => ['failure', 'timed_out', 'cancelled'].includes(c.conclusion)) ? 'vermelho' : runs.length ? 'verde' : 'sem-teste';
      }
      return {
        numero: pr.number, titulo: String(pr.title || '').slice(0, 120), link: pr.html_url, ramo: pr.head.ref,
        estado: pr.merged_at ? 'juntado' : pr.state === 'open' ? (pr.draft ? 'rascunho' : 'aberto') : 'fechado',
        ci, automerge: nomes(pr).includes('automerge'), quando: pr.updated_at,
      };
    }));
  }

  async function detalhe(n) {
    const i = await gh('/repos/' + REPO + '/issues/' + Number(n));
    if (i.pull_request) throw new Error('Isso é um PR, não um pedido.');
    const [coms, prs] = await Promise.all([
      gh('/repos/' + REPO + '/issues/' + i.number + '/comments?per_page=100'),
      prsDe(i).catch(() => []),
    ]);
    
    // Verificar se o pedido tem os rótulos e comentários necessários
    const rotulos = nomes(i);
    const temRotuloNecessario = rotulos.includes('cortex-dividido') || rotulos.includes('cortex-feito');
    const temComentarioPlano = coms.some(c => String(c.body || '').includes('montei um plano'));
    
    let partes = [];
    if (temRotuloNecessario && temComentarioPlano) {
      // Buscar as partes correspondentes
      const query = 'repo:' + REPO + ' is:issue in:title "de #' + i.number + ']"';
      const resultadoBusca = await busca(query);
      
      if (resultadoBusca && resultadoBusca.items) {
        // Processar cada parte
        const partesProcessadas = await Promise.all(
          resultadoBusca.items.map(async (parte) => {
            // Extrair o número k do título [Parte k/n de #N]
            const match = String(parte.title || '').match(/\[Parte (\d+)\/\d+ de #\d+\]/);
            const k = match ? parseInt(match[1], 10) : 0;
            
            // Determinar o estado
            const rotulosParte = nomes(parte);
            let estado = 'esperando';
            if (rotulosParte.includes('cortex-feito')) estado = 'feita';
            else if (rotulosParte.includes('cortex-rodando')) estado = 'rodando';
            else if (rotulosParte.includes('cortex-travada')) estado = 'travada';
            else if (rotulosParte.includes('cortex-jules') || rotulosParte.includes('jules-enviado')) estado = 'no Jules';
            
            // Determinar a pista
            const pistaMatch = rotulosParte.find(r => r.startsWith('pista-'));
            const pista = pistaMatch ? parseInt(pistaMatch.replace('pista-', ''), 10) || null : null;
            
            // Ler o cabeçalho do plano
            const plano = require('../../../scripts/cortex-plano').lerPlano(parte.body);
            const depende = plano && plano.depende ? plano.depende : [];
            const arquivos = plano && plano.arquivos ? plano.arquivos : [];
            
            return {
              numero: parte.number,
              titulo: String(parte.title || '').slice(0, 120),
              link: parte.html_url,
              estado,
              pista,
              depende,
              arquivos,
              quando: parte.updated_at
            };
          })
        );
        
        // Ordenar as partes pelo número k
        partes = partesProcessadas.sort((a, b) => a.numero - b.numero);
      }
    }
    
    const conversa = [{ quem: (i.user || {}).login || '?', quando: i.created_at, texto: limpar(i.body) }]
      .concat(coms.map((c) => ({ quem: (c.user || {}).login || '?', quando: c.created_at, texto: String(c.body || '').replace(/\n---\n_Generated by[^\n]*_\s*$/, '').trim().replace(RODAPE, '').trim() })));
    
    return { ...resumo(i), rotulos: nomes(i), conversa, prs, partes };
  }

  return detalhe;
}

module.exports = { criarDetalhe };
