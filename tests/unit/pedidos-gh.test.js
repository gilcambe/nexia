'use strict';
const test = require('node:test');
const assert = require('node:assert');
const { criarPedidos, situacao, frase } = require('../../netlify/functions/central/pedidos-gh.js');
const { criarDetalhe } = require('../../netlify/functions/central/pedidos-detalhe.js');

test('PED6. situação e frase de busca', () => {
  assert.strictEqual(situacao({ state: 'open', labels: [{ name: 'cortex-travado' }] }), 'travado');
  assert.strictEqual(situacao({ state: 'closed', labels: [{ name: 'cortex-feito' }] }), 'feito');
  assert.strictEqual(frase('Pré-requisito: a "API" (x)'), 'Pré-requisito a API x');
});

test('PED7. lista e detalhe usam a busca do GitHub e juntam os PRs', async () => {
  const urls = [];
  const fetchFn = async (u) => {
    urls.push(u);
    const j = u.includes('/search/issues') && u.includes('is%3Apr') ? { items: [{ number: 3 }] }
      : u.includes('/search/issues') ? { total_count: 1, items: [{ number: 1, title: 't', state: 'open', labels: [] }] }
      : u.endsWith('/issues/1') ? { number: 1, body: 'Fazer a página', state: 'open', labels: [], user: { login: 'gilcambe' } }
      : u.includes('/comments') ? [{ user: { login: 'bot' }, body: 'ok\n\n---\n_Generated by [Claude Code](x)_' }]
      : u.endsWith('/pulls/3') ? { number: 3, state: 'closed', merged_at: 'x', head: { ref: 'nexia/a', sha: 's' }, labels: [] } : {};
    return { ok: true, status: 200, json: async () => j };
  };
  const p = criarPedidos({ NEXIA_JOBS_TOKEN: 't' }, fetchFn);
  const l = await p.lista({ estado: 'travados' });
  assert.strictEqual(l.itens[0].situacao, 'fila');
  assert.ok(decodeURIComponent(urls[0]).includes('label:cortex-travado'));
  const d = await criarDetalhe(p.gh)(1);
  assert.strictEqual(d.conversa.length, 2); assert.strictEqual(d.conversa[1].texto, 'ok');
  assert.strictEqual(d.prs[0].estado, 'juntado');
});
